

FREYTAG_PYRAMID = """
Classical Five-Act Tragedy Structure

ACT I - EXPOSITION (20%):
- Introduce protagonist in their ordinary world
- Establish setting, tone, and initial character dynamics
- Plant seeds of the central conflict
- Show what's at stake in the protagonist's normal life
- End with the INCITING INCIDENT that disrupts equilibrium

ACT II - RISING ACTION (25%):
- Protagonist commits to addressing the conflict
- Introduce complications and obstacles
- Develop secondary characters and subplots
- Escalate tension through progressive challenges
- Each scene should raise stakes higher than the last
- Build toward the climax through accumulating pressure

ACT III - CLIMAX (10%):
- The point of highest dramatic tension
- Protagonist faces the ultimate test
- All conflicts converge in this moment
- The turning point where success or failure is determined
- Often involves a critical choice or revelation
- Should be the most intense, focused section

ACT IV - FALLING ACTION (25%):
- Deal with immediate consequences of the climax
- Resolve secondary plot threads
- Show the aftermath and new reality
- Address lingering character arcs
- Tension decreases but meaning deepens

ACT V - DENOUEMENT/RESOLUTION (20%):
- Restore equilibrium (new normal, not old normal)
- Show how characters have transformed
- Deliver thematic payoff
- Provide emotional closure
- Answer remaining questions
- End with a sense of completion

CREATIVE FLEXIBILITY:
- Acts can blend at boundaries for modern pacing
- Climax placement can shift for genre (thriller: later, literary: earlier)
- Multiple mini-climaxes can precede the ultimate climax
- Subplots can have independent Freytag arcs within main structure
"""

