DAN_HARMON_STORY_CIRCLE = """
Based on eight fundamental story beats in circular narrative:

1. YOU - A Character in a Zone of Comfort (12.5%):
   - Establish protagonist in familiar world
   - Show their normal routine
   - Hint at underlying dissatisfaction or need
   - Character is incomplete but doesn't fully know it
   
   CREATIVE NOTES:
   - Can be brief in action genres, extended in character studies
   - Comfort can be false comfort (denial, ignorance)
   - Sets baseline for measuring change

2. NEED - But They Want Something (12.5%):
   - Identify what protagonist desires
   - This want may not be what they truly need
   - Creates motivation for movement
   - Often external goal (want) vs internal need
   
   CREATIVE NOTES:
   - Want and need can be at odds (creates internal conflict)
   - Multiple characters can want the same thing
   - Desire should feel urgent and specific

3. GO - They Enter an Unfamiliar Situation (12.5%):
   - Protagonist crosses threshold
   - Enters new physical or psychological space
   - Leaves comfort zone behind
   - Commits to pursuit of desire
   
   CREATIVE NOTES:
   - Can be literal journey or internal transformation
   - Risk and uncertainty introduced
   - Allies and enemies met in new world

4. SEARCH - Adapt to It (12.5%):
   - Protagonist experiments, explores, struggles
   - Learns new rules
   - Faces tests and challenges
   - Experiences small wins and losses
   
   CREATIVE NOTES:
   - Longest phase, can be subdivided
   - Character growth happens through trial and error
   - Subplots flourish here

5. FIND - Get What They Wanted (12.5%):
   - Protagonist achieves goal or seems to
   - Climactic moment of success
   - Obtains the object of desire
   - But victory may be hollow or incomplete
   
   CREATIVE NOTES:
   - Can be false victory
   - Success brings new complications
   - Realization that want ≠ need

6. TAKE - Pay a Heavy Price for It (12.5%):
   - Consequences of actions revealed
   - Sacrifice required
   - Loss of something valuable
   - Protagonist faces cost of their choices
   
   CREATIVE NOTES:
   - Price can be physical, emotional, moral
   - Relationships tested or broken
   - Moment of truth about character

7. RETURN - Then Return to Familiar Situation (12.5%):
   - Protagonist heads back to starting world
   - Brings prize or lesson with them
   - Journey home can be literal or metaphorical
   - May face final obstacles
   
   CREATIVE NOTES:
   - Return is never to exact same place
   - May be chased or pursued
   - Anticipation of how change will affect home

8. CHANGE - Having Changed (12.5%):
   - Demonstrate transformation
   - Character now has what they needed (not just wanted)
   - New equilibrium established
   - Growth evident in choices and perspective
   
   CREATIVE NOTES:
   - Change should be earned, not declared
   - Show don't tell the transformation
   - New comfort zone reflects growth

CIRCULAR NATURE:
- Story ends where it began (but different)
- Can nest multiple circles within overall arc
- Each character can have their own circle
- Subplots follow mini-circles

CREATIVE FLEXIBILITY:
- Beats can vary in length based on story needs
- Can move through circle multiple times (episodic)
- Works for comedy, drama, action, any genre
- Can be applied to scene-level structure
- Multiple perspectives can each complete their own circle
"""

