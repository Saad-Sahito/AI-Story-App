class SceneOutlinerAgent:
    """Converts Director's abstract directives into concrete prose outline"""
    
    def __init__(self):
        self.parser = PydanticOutputParser(pydantic_object=ProseOutline)
    
    async def create_prose_outline(
        self,
        directive: Dict[str, Any],
        scene_target_length: int,
        llm_temp: float,
        model: str,
        token_usage: Dict[str, int]
    ) -> Tuple[ProseOutline, Dict[str, int]]:
        """Convert Director's directive into paragraph-by-paragraph outline"""
        
        # Calculate paragraph breakdown
        avg_paragraph_length = 120  # Target average
        estimated_paragraphs = max(3, min(12, scene_target_length // avg_paragraph_length))
        
        system_prompt = f"""You are a Scene Outliner converting a Director's vision into a concrete prose outline.

The Director has provided abstract creative guidance. Your job is to translate this into a SPECIFIC paragraph-by-paragraph plan that a writer can execute.

For each paragraph:
1. Define a clear objective (what story purpose it serves)
2. Write out the opening sentence exactly
3. List 2-3 specific events/actions that happen
4. Specify sensory details to include (with exact descriptions)
5. Note if dialogue is present and who speaks
6. Describe emotional tone/shift
7. Plan the transition to next paragraph

Be CONCRETE. Instead of "show character's fear", write "Sarah's hands tremble as she reaches for the doorknob, sweat beading on her forehead."

Target: {estimated_paragraphs} paragraphs totaling ~{scene_target_length} words

{self.parser.get_format_instructions()}"""

        human_prompt = f"""Create a detailed prose outline from this directive:

DIRECTOR'S VISION:
Author Intent: {directive.get('author_intent', 'N/A')}
Opening Image: {directive.get('opening_image', '')}
Scene Blocking: {directive.get('scene_blocking', '')}
Pacing: {directive.get('pacing_direction', '')}
Dialogue Guidance: {directive.get('dialogue_guidance', '')}
Sensory Palette: {', '.join(directive.get('sensory_palette', []))}
Emotional Camera: {directive.get('emotional_camera', '')}
Rhythm: {directive.get('scene_rhythm', '')}
Must Include: {', '.join(directive.get('key_details_to_include', []))}
Closing Image: {directive.get('closing_image', '')}
Style: {directive.get('style_adjustments', '')}

Generate {estimated_paragraphs} paragraph outlines with specific, executable instructions."""

        try:
            response, tokens = await writer_client(
                system_prompt=system_prompt,
                human_prompt=human_prompt,
                llm_temp=llm_temp,
                model=model
            )
            
            token_usage["prompt_tokens"] += tokens["prompt_tokens"]
            token_usage["completion_tokens"] += tokens["completion_tokens"]
            token_usage["total_tokens"] += tokens["total_tokens"]
            
            clean_resp = StoryHelpers._extract_content(response)
            clean_resp = StoryHelpers._strip_code_fences(clean_resp)
            
            json_data = await StoryHelpers.load_json_with_retry(clean_resp, self.parser)
            outline = self.parser.parse(json_data)
            
            print(f"✅ Prose outline created: {outline.total_paragraphs} paragraphs planned")
            return outline, token_usage
            
        except Exception as e:
            print(f"❌ Scene Outliner failed: {e}")
            traceback.print_exc()
            raise


