# AGE APPROPRIATE VALIDATOR
# ============================================================================

class AgeAppropriateValidator:
    """Validates content appropriateness for target age using readability metrics"""
    
    # Age to Flesch-Kincaid grade level mapping
    AGE_TO_GRADE = {
        8: 3.0,   # 3rd grade
        9: 4.0,   # 4th grade
        10: 5.0,  # 5th grade
        11: 6.0,  # 6th grade
        12: 7.0,  # 7th grade
        13: 8.0,  # 8th grade
        14: 9.0,  # 9th grade
        15: 10.0, # 10th grade
        16: 11.0, # 11th grade
        17: 12.0, # 12th grade
        18: 13.0  # College level
    }
    
    # Content keywords to flag by age
    SENSITIVE_KEYWORDS = {
        "violence": ["blood", "gore", "mutilated", "dismember", "torture", "slaughter"],
        "mature_themes": ["sexual", "seductive", "arousal", "explicit"],
        "strong_language": ["damn", "hell", "bastard", "bitch"],  # Mild profanity
        "dark_themes": ["suicide", "self-harm", "overdose", "rape"]
    }
    
    AGE_RESTRICTIONS = {
        8: {"block": ["violence", "mature_themes", "strong_language", "dark_themes"]},
        9: {"block": ["violence", "mature_themes", "strong_language", "dark_themes"]},
        10: {"block": ["violence", "mature_themes", "strong_language", "dark_themes"]},
        11: {"block": ["mature_themes", "strong_language", "dark_themes"], "warn": ["violence"]},
        12: {"block": ["mature_themes", "dark_themes"], "warn": ["violence", "strong_language"]},
        13: {"block": ["mature_themes", "dark_themes"], "warn": ["violence", "strong_language"]},
        14: {"block": ["mature_themes"], "warn": ["dark_themes", "violence"]},
        15: {"warn": ["mature_themes", "dark_themes"]},
        16: {"warn": ["mature_themes", "dark_themes"]},
        17: {"warn": ["mature_themes"]},
        18: {}  # No restrictions
    }
    
    @staticmethod
    def get_target_grade(age: int) -> float:
        """Get target Flesch-Kincaid grade for age"""
        return AgeAppropriateValidator.AGE_TO_GRADE.get(age, 8.0)
    
    @staticmethod
    def calculate_readability(text: str) -> Dict[str, float]:
        """Calculate multiple readability metrics"""
        if len(text.strip()) < 100:  # Too short for reliable metrics
            return {
                "flesch_kincaid_grade": 5.0,
                "flesch_reading_ease": 80.0,
                "gunning_fog": 8.0
            }
        
        try:
            return {
                "flesch_kincaid_grade": textstat.flesch_kincaid_grade(text),
                "flesch_reading_ease": textstat.flesch_reading_ease(text),
                "gunning_fog": textstat.gunning_fog(text)
            }
        except Exception as e:
            print(f"⚠️ Readability calculation error: {e}")
            return {
                "flesch_kincaid_grade": 8.0,
                "flesch_reading_ease": 70.0,
                "gunning_fog": 10.0
            }
    
    @staticmethod
    def detect_sensitive_content(text: str, age: int) -> Dict[str, List[str]]:
        """Detect sensitive content based on age restrictions"""
        text_lower = text.lower()
        detected = {"blocked": [], "warnings": []}
        
        restrictions = AgeAppropriateValidator.AGE_RESTRICTIONS.get(age, {})
        blocked_categories = restrictions.get("block", [])
        warn_categories = restrictions.get("warn", [])
        
        for category, keywords in AgeAppropriateValidator.SENSITIVE_KEYWORDS.items():
            found_keywords = [kw for kw in keywords if kw in text_lower]
            
            if found_keywords:
                if category in blocked_categories:
                    detected["blocked"].append(f"{category}: {', '.join(found_keywords)}")
                elif category in warn_categories:
                    detected["warnings"].append(f"{category}: {', '.join(found_keywords)}")
        
        return detected
    
    @staticmethod
    def validate_content(text: str, target_age: int) -> AgeAppropriateReport:
        """Comprehensive content validation"""
        target_grade = AgeAppropriateValidator.get_target_grade(target_age)
        readability = AgeAppropriateValidator.calculate_readability(text)
        sensitive = AgeAppropriateValidator.detect_sensitive_content(text, target_age)
        
        actual_grade = readability["flesch_kincaid_grade"]
        grade_diff = actual_grade - target_grade
        
        issues = []
        warnings = []
        recommendations = []
        
        # Check readability
        if grade_diff > 2.0:
            issues.append(f"Text too complex: grade {actual_grade:.1f} vs target {target_grade:.1f}")
            recommendations.append("Simplify sentence structure and vocabulary")
        elif grade_diff > 1.0:
            warnings.append(f"Text slightly complex: grade {actual_grade:.1f} vs target {target_grade:.1f}")
            recommendations.append("Consider shorter sentences")
        
        # Check sensitive content
        if sensitive["blocked"]:
            issues.extend(sensitive["blocked"])
            recommendations.append("Remove or rephrase flagged content for age group")
        
        if sensitive["warnings"]:
            warnings.extend(sensitive["warnings"])
            recommendations.append("Review flagged content for age-appropriateness")
        
        # Check sentence length for younger audiences
        if target_age <= 12:
            avg_sentence_length = textstat.avg_sentence_length(text)
            if avg_sentence_length > 20:
                warnings.append(f"Average sentence length {avg_sentence_length:.1f} may be too long")
                recommendations.append("Break long sentences into shorter ones")
        
        is_appropriate = len(issues) == 0 and len(sensitive["blocked"]) == 0
        
        return AgeAppropriateReport(
            is_appropriate=is_appropriate,
            readability_grade=actual_grade,
            target_grade=target_grade,
            issues=issues,
            warnings=warnings,
            recommendations=recommendations
        )


