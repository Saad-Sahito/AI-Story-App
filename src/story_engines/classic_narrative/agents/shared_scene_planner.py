class ScenePlannerService:
    def __init__(self):
        self.paragraph_parser = PydanticOutputParser(pydantic_object=ParagraphOutput)
        self.outliner = SceneOutlinerAgent()
        self.validator = AgeAppropriateValidator()
        
        # Build paragraph writer system prompt
        self.paragraph_writer_system = """You are a Paragraph Writer executing a detailed prose outline.

CRITICAL RULES:
1. Write EXACTLY ONE paragraph (60-200 words)
2. Follow the outline's objective precisely
3. Use the provided opening sentence or very similar
4. Include all specified sensory details and events
5. Maintain consistent character voices
6. Respect the emotional tone
7. Create smooth transition as specified

OUTPUT REQUIREMENTS:
- Valid JSON only
- 'paragraph_text': The prose paragraph
- 'word_count': Actual word count
- 'next_action': "Continue" or "End"

Write beautiful, engaging prose that brings the outline to life."""

        # Build graph
        self.graph = StateGraph(SceneState)
        self.graph.add_node("Initializer", self._initializer)
        self.graph.add_node("SceneOutliner", self._scene_outliner)
        self.graph.add_node("ParagraphWriter", self._paragraph_writer)
        self.graph.add_node("ContentValidator", self._content_validator)
        
        self.graph.set_entry_point("Initializer")
        self.graph.add_edge("Initializer", "SceneOutliner")
        self.graph.add_edge("SceneOutliner", "ParagraphWriter")
        
        def writer_decider(state: SceneState):
            if getattr(state, "fatal", False) or getattr(state, "next_node", None) == "FATAL_ERROR":
                return "FATAL_ERROR"
            
            next_action = getattr(state, "next_node", "End")
            if next_action == "Continue":
                return "ParagraphWriter"
            elif next_action == "Validate":
                return "ContentValidator"
            return "END"
        
        self.graph.add_conditional_edges(
            "ParagraphWriter",
            writer_decider,
            {
                "ParagraphWriter": "ParagraphWriter",
                "ContentValidator": "ContentValidator",
                "END": END,
                "FATAL_ERROR": END
            }
        )
        
        def validator_decider(state: SceneState):
            if getattr(state, "fatal", False):
                return "FATAL_ERROR"
            return "END"
        
        self.graph.add_conditional_edges(
            "ContentValidator",
            validator_decider,
            {
                "END": END,
                "FATAL_ERROR": END
            }
        )
        
        self.compiled = self.graph.compile()
    
    def _handle_fatal_error(self, state: SceneState, error: Exception, stage: str) -> SceneState:
        state.fatal = True
        state.next_node = "FATAL_ERROR"
        state.error_type = stage
        state.error_message = f"{type(error).__name__}: {str(error)}"
        print(f"❌ [FATAL] {stage} failed – {state.error_message}")
        traceback.print_exc()
        return state
    
    async def run_scene(self, user_context: UserSceneContext, stop_event: asyncio.Event | None = None) -> Tuple[str, list, str, dict]:
        print(f"🎭 Starting enhanced run_scene for {user_context.user_id}/{user_context.story_id}")
        
        try:
            user_context.scene_state.user_context_id = user_context.user_id
        except Exception as e:
            print(f"❌ Failed to set user_context_id: {e}")
            traceback.print_exc()
            return "", [], f"EXCEPTION: {type(e).__name__}: {e}", user_context.scene_state.token_usage
        
        try:
            task = asyncio.create_task(
                self.compiled.ainvoke(user_context.scene_state, {"recursion_limit": 30, "stop_event": stop_event})
            )
            
            while not task.done():
                if stop_event and stop_event.is_set():
                    print("🛑 Stop event received – cancelling SceneGraph task...")
                    task.cancel()
                    try:
                        await task
                    except asyncio.CancelledError:
                        print("✅ SceneGraph task cancelled cleanly")
                    return "", [], "CANCELLED", user_context.scene_state.token_usage
                await asyncio.sleep(0.2)
            
            result = await task
            if not isinstance(result, dict):
                user_context.scene_state = result
            else:
                user_context.scene_state = SceneState(**result)
            
            next_node = getattr(result, "next_node", None) if not isinstance(result, dict) else result.get("next_node")
            error_message = getattr(result, "error_message", None) if not isinstance(result, dict) else result.get("error_message")
            scene_memory = getattr(result, "scene_memory", None) if not isinstance(result, dict) else result.get("scene_memory")
            
            if getattr(result, "fatal", False) or next_node == "FATAL_ERROR":
                fatal_msg = error_message or "Unknown fatal error"
                print(f"❌ Scene aborted due to fatal error: {fatal_msg}")
                return "", [], f"FATAL: {fatal_msg}", user_context.scene_state.token_usage
            
            if scene_memory is None:
                print("⚠️ Warning: LangGraph returned with no scene_memory.")
                return "", [], "EXCEPTION: No scene_memory returned", user_context.scene_state.token_usage
            
            scene_so_far = getattr(scene_memory, "scene_so_far", "") if not isinstance(scene_memory, dict) else scene_memory.get("scene_so_far", "")
            scene_cluster = getattr(scene_memory, "scene_cluster", []) if not isinstance(scene_memory, dict) else scene_memory.get("scene_cluster", [])
            
            print("✅ Scene completed normally")
            return scene_so_far, scene_cluster, "SUCCESS", user_context.scene_state.token_usage
        
        except asyncio.CancelledError:
            print("🛑 SceneGraph CancelledError caught")
            return "", [], "CANCELLED", user_context.scene_state.token_usage
        except Exception as e:
            print(f"❌ ERROR in run_scene: {e}")
            traceback.print_exc()
            return "", [], f"EXCEPTION: {type(e).__name__}: {e}", user_context.scene_state.token_usage
        finally:
            print("🎭 SceneGraph stopped gracefully")
            gc.collect()
    
    def _initializer(self, state: SceneState) -> SceneState:
        print(f"🔧 Initializer node for user_context_id={state.user_context_id}, age={state.user_age}")
        if getattr(state, "fatal", False):
            return state
        state.next_node = "SceneOutliner"
        return state
    
    async def _scene_outliner(self, state: SceneState) -> SceneState:
        """Generate detailed prose outline from Director's directive"""
        print(f"📋 Scene Outliner generating prose outline...")
        
        if getattr(state, "fatal", False):
            return state
        
        scene_memory: SceneMemory = state.scene_memory
        
        try:
            directive = json.loads(scene_memory.DirectorInstructions)
            
            outline, token_usage = await self.outliner.create_prose_outline(
                directive=directive,
                scene_target_length=state.scene_target_length,
                llm_temp=state.llm_temp,
                model=state.model,
                token_usage=state.token_usage
            )
            
            scene_memory.prose_outline = outline
            state.scene_memory = scene_memory
            state.token_usage = token_usage
            state.next_node = "ParagraphWriter"
            
            print(f"✅ Outline complete: {outline.total_paragraphs} paragraphs planned")
            
            return state
            
        except Exception as e:
            return self._handle_fatal_error(state, e, "SceneOutliner")
    
    async def _paragraph_writer(self, state: SceneState) -> SceneState:
        """Write one paragraph at a time following the outline"""
        print(f"✍️ Writing paragraph {state.scene_memory.current_paragraph_number}")
        
        if getattr(state, "fatal", False):
            return state
        
        scene_memory: SceneMemory = state.scene_memory
        prose_outline: ProseOutline = scene_memory.prose_outline
        
        # Check if we're done
        if scene_memory.current_paragraph_number > prose_outline.total_paragraphs:
            print(f"✅ All {prose_outline.total_paragraphs} paragraphs written")
            state.next_node = "Validate"
            return state
        
        # Circuit breaker
        if state.iteration_count > 20:
            print(f"🛑 FORCE END: Exceeded max iterations")
            state.next_node = "Validate"
            return state
        
        # Get current paragraph outline
        current_para = prose_outline.paragraphs[scene_memory.current_paragraph_number - 1]
        
        # Build context-aware prompt
        human_prompt = f"""Write paragraph {scene_memory.current_paragraph_number} of {prose_outline.total_paragraphs}.

PARAGRAPH OUTLINE:
Objective: {current_para.objective}
Opening sentence: {current_para.opening_sentence}
Key events: {', '.join(current_para.key_events)}
Sensory details to include: {', '.join(current_para.sensory_details)}
Dialogue: {"Yes - " + ', '.join(current_para.dialogue_agents) if current_para.dialogue_present else "No"}
Emotional tone: {current_para.emotional_note}
Transition: {current_para.transition_to_next}
Target words: {current_para.target_word_count}

PREVIOUS TEXT:
{scene_memory.scene_so_far[-500:] if scene_memory.scene_so_far else "[Scene starting now]"}

VOICE REMINDERS:
{json.dumps(prose_outline.voice_notes, indent=2)}

Write this paragraph following the outline exactly. Output valid JSON only:
{self.paragraph_parser.get_format_instructions()}"""
        
        try:
            response, tokens = await writer_client(
                system_prompt=self.paragraph_writer_system,
                human_prompt=human_prompt,
                llm_temp=state.llm_temp,
                model=state.model
            )
            
            state.token_usage["prompt_tokens"] += tokens["prompt_tokens"]
            state.token_usage["completion_tokens"] += tokens["completion_tokens"]
            state.token_usage["total_tokens"] += tokens["total_tokens"]
            
            clean_resp = StoryHelpers._extract_content(response)
            clean_resp = StoryHelpers._strip_code_fences(clean_resp)
            
            try:
                parsed = self.paragraph_parser.parse(clean_resp)
                paragraph_text = parsed.paragraph_text
                word_count = parsed.word_count
            except Exception as e:
                print(f"⚠️ Parser failed, attempting JSON fix: {e}")
                fixed_json = await StoryHelpers._json_fixer(clean_resp)
                try:
                    parsed = self.paragraph_parser.parse(fixed_json)
                    paragraph_text = parsed.paragraph_text
                    word_count = parsed.word_count
                except Exception as repair_e:
                    print(f"❌ JSON fixer failed: {repair_e}")
                    match = re.search(r'"paragraph_text"\s*:\s*"([^"]*)"', clean_resp)
                    paragraph_text = match.group(1) if match else ""
                    word_count = StoryHelpers._count_words_split(paragraph_text)
            
            # Update scene memory
            actual_word_count = StoryHelpers._count_words_split(paragraph_text)
            scene_memory.word_count += actual_word_count
            scene_memory.scene_cluster.append({
                "type": "text",
                "scene_text": paragraph_text,
                "word_count": actual_word_count,
                "paragraph_number": scene_memory.current_paragraph_number
            })
            scene_memory.scene_so_far += ("\n\n" + paragraph_text)
            
            print(f"📝 Paragraph {scene_memory.current_paragraph_number}: {actual_word_count} words | Total: {scene_memory.word_count}/{state.scene_target_length}")
            
            # Send to frontend
            if state.scene_chunk_callback:
                try:
                    state.scene_chunk_callback({
                        "type": "text",
                        "scene_text": paragraph_text
                    })
                    state.scene_chunk_callback({
                        "type": "status",
                        "word_count": actual_word_count,
                        "total_word_count": scene_memory.word_count,
                        "target_word_count": state.scene_target_length,
                        "completion_percentage": int((scene_memory.word_count / state.scene_target_length) * 100),
                        "paragraph_number": scene_memory.current_paragraph_number,
                        "total_paragraphs": prose_outline.total_paragraphs
                    })
                except Exception as e:
                    print(f"❌ Callback failed: {e}")
            
            # Move to next paragraph
            scene_memory.current_paragraph_number += 1
            state.scene_memory = scene_memory
            state.iteration_count += 1
            
            # Decide next action
            if scene_memory.current_paragraph_number > prose_outline.total_paragraphs:
                state.next_node = "Validate"
            else:
                state.next_node = "Continue"
            
            del response, clean_resp, tokens
            gc.collect()
            return state
            
        except asyncio.TimeoutError as e:
            return self._handle_fatal_error(state, e, "ParagraphWriter Timeout")
        except Exception as e:
            return self._handle_fatal_error(state, e, "ParagraphWriter")
    
    async def _content_validator(self, state: SceneState) -> SceneState:
        """Validate final scene content for age-appropriateness"""
        print(f"🔍 Validating content for age {state.user_age}...")
        
        if getattr(state, "fatal", False):
            return state
        
        scene_memory: SceneMemory = state.scene_memory
        full_scene_text = scene_memory.scene_so_far
        
        try:
            # Run validation
            report = self.validator.validate_content(full_scene_text, state.user_age)
            
            print(f"📊 Readability: {report.readability_grade:.1f} (target: {report.target_grade:.1f})")
            
            if report.issues:
                print(f"⚠️ Content Issues Found:")
                for issue in report.issues:
                    print(f"   - {issue}")
            
            if report.warnings:
                print(f"⚠️ Content Warnings:")
                for warning in report.warnings:
                    print(f"   - {warning}")
            
            if report.recommendations:
                print(f"💡 Recommendations:")
                for rec in report.recommendations:
                    print(f"   - {rec}")
            
            # Add validation report to scene cluster
            scene_memory.scene_cluster.append({
                "type": "validation_report",
                "is_appropriate": report.is_appropriate,
                "readability_grade": report.readability_grade,
                "target_grade": report.target_grade,
                "issues": report.issues,
                "warnings": report.warnings,
                "recommendations": report.recommendations
            })
            
            # Send validation to frontend
            if state.scene_chunk_callback:
                try:
                    state.scene_chunk_callback({
                        "type": "validation",
                        "is_appropriate": report.is_appropriate,
                        "readability_grade": round(report.readability_grade, 1),
                        "target_grade": round(report.target_grade, 1),
                        "issues_count": len(report.issues),
                        "warnings_count": len(report.warnings)
                    })
                except Exception as e:
                    print(f"❌ Validation callback failed: {e}")
            
            state.scene_memory = scene_memory
            
            if report.is_appropriate:
                print("✅ Content validated successfully")
            else:
                print("⚠️ Content has issues but proceeding (manual review recommended)")
            
            state.next_node = "End"
            return state
            
        except Exception as e:
            print(f"⚠️ Content validation failed: {e}")
            traceback.print_exc()
            # Don't fail the whole scene for validation errors
            state.next_node = "End"
            return state


