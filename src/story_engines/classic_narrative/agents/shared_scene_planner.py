class ParagraphOutline(BaseModel):
    """Detailed outline for a single paragraph"""
    paragraph_number: int = Field(description="Sequential paragraph number")
    objective: str = Field(description="What this paragraph accomplishes")
    opening_sentence: str = Field(description="First sentence written out")
    key_events: List[str] = Field(description="2-3 specific things that happen")
    sensory_details: List[str] = Field(description="Specific sensory elements to include")
    dialogue_present: bool = Field(description="Does this paragraph contain dialogue?")
    dialogue_agents: Optional[List[str]] = Field(default=None, description="Who speaks if dialogue present")
    emotional_note: str = Field(description="Emotional tone/shift in this paragraph")
    transition_to_next: str = Field(description="How to flow into next paragraph")
    target_word_count: int = Field(description="Target words for this paragraph", ge=60, le=200)


class ProseOutline(BaseModel):
    """Complete prose outline for a scene"""
    scene_id: int
    total_paragraphs: int = Field(description="Number of paragraphs in scene")
    paragraphs: List[ParagraphOutline] = Field(description="Detailed paragraph-by-paragraph plan")
    opening_image_execution: str = Field(description="Exactly how to open the scene")
    closing_image_execution: str = Field(description="Exactly how to close the scene")
    pacing_strategy: str = Field(description="Concrete pacing approach")
    voice_notes: Dict[str, str] = Field(description="Agent name -> specific voice reminders")


class ParagraphOutput(BaseModel):
    """Single paragraph generated by writer"""
    paragraph_text: str = Field(description="The prose paragraph (60-200 words)")
    word_count: int = Field(description="Actual word count")
    next_action: str = Field(description="'Continue' or 'End'")


class AgeAppropriateReport(BaseModel):
    """Content validation report"""
    is_appropriate: bool = Field(description="Whether content passes age filter")
    readability_grade: float = Field(description="Flesch-Kincaid grade level")
    target_grade: float = Field(description="Target grade level for age")
    issues: List[str] = Field(default_factory=list, description="Problems detected")
    warnings: List[str] = Field(default_factory=list, description="Potential concerns")
    recommendations: List[str] = Field(default_factory=list, description="Suggested adjustments")


class SceneMemory(BaseModel):
    DirectorInstructions: Any = Field(description="Director's instructions for this scene.")
    prose_outline: Optional[ProseOutline] = Field(default=None, description="Detailed prose outline")
    scene_so_far: str = Field(default="", description="Accumulated text of the scene.")
    scene_cluster: List = Field(default=[], description="Scene text, questions, and user choices as dicts.")
    word_count: int = Field(..., description="Word count of the scene.")
    story_id: Optional[str] = Field(default="", description="Story ID for this scene.")
    current_paragraph_number: int = Field(default=1, description="Which paragraph we're writing")


class SceneState(BaseModel):
    scene_memory: Optional[SceneMemory] = None
    next_node: Optional[str] = None
    user_context_id: Optional[str] = Field(default=None, description="User ID for this scene")
    user_age: int = Field(default=13, description="Target audience age")
    iteration_count: int = 0
    scene_chunk_callback: Optional[Callable] = Field(default=None, description="Callback for frontend updates")
    error_type: Optional[str] = None
    error_message: Optional[str] = None
    fatal: bool = False
    llm_temp: float = Field(default=0.7, description="Temperature for LLM")
    model: str = Field(default="None", description="Model name for LLM")
    token_usage: dict = Field(default_factory=lambda: {"prompt_tokens": 0, "completion_tokens": 0, "total_tokens": 0})
    target_length: int = Field(default=500, description="Target length for the story")
    scene_target_length: int = Field(default=500, description="Target length for this scene")

    class Config:
        extra = "allow"


@dataclass
class UserSceneContext:
    user_id: str
    story_id: str
    director_instructions: Any
    scene_state: SceneState
    scene_memory: SceneMemory
    scene_chunk_callback: Callable

    @classmethod
    def create_for_user(cls, user_id: str, story_id: str, director_instructions: str, 
                       scene_chunk_callback: Callable, llm_temp: float = 0.7, model: str = "None",
                       token_usage: dict = None, target_length: int = 500, 
                       scene_target_length: int = 500, user_age: int = 13):
        token_usage = token_usage or {"prompt_tokens": 0, "completion_tokens": 0, "total_tokens": 0}
        
        scene_memory = SceneMemory(
            DirectorInstructions=director_instructions.strip(),
            scene_so_far="",
            story_id=story_id,
            word_count=0,
            current_paragraph_number=1
        )

        scene_state = SceneState(
            scene_memory=scene_memory,
            next_node=None,
            user_context_id=user_id,
            user_age=user_age,
            scene_chunk_callback=scene_chunk_callback,
            llm_temp=llm_temp,
            model=model,
            token_usage=token_usage,
            target_length=target_length,
            scene_target_length=scene_target_length
        )

        return cls(
            user_id=user_id,
            story_id=story_id,
            director_instructions=director_instructions,
            scene_state=scene_state,
            scene_memory=scene_memory,
            scene_chunk_callback=scene_chunk_callback
        )


